<?php
declare(strict_types=1);

namespace app\exception\handler;

use app\exception\BusinessException;
use think\db\exception\DataNotFoundException;
use think\db\exception\ModelNotFoundException;
use think\exception\Handle;
use think\exception\HttpException;
use think\exception\HttpResponseException;
use think\exception\ValidateException;
use think\Response;
use Throwable;

class AppExceptionHandler extends Handle
{
    /**
     * 不需要记录信息（日志）的异常类列表
     * @var string[]
     */
    protected $ignoreReport = [
        HttpException::class,
        HttpResponseException::class,
        ModelNotFoundException::class,
        DataNotFoundException::class,
        ValidateException::class,
    ];

    /**
     * 记录异常信息（包括日志或者其它方式记录）
     * @param Throwable $exception
     * @return void
     */
    public function report(Throwable $exception): void
    {
        parent::report($exception); // TODO: Change the autogenerated stub
    }

    /**
     * @param $request
     * @param Throwable $e
     * @return Response
     */
    public function render($request, Throwable $e): Response
    {
        // The panel speaks JSON only over its AJAX endpoints. A plain browser
        // navigation that trips a thrown validation/business error must still
        // render the normal error page instead of a bare JSON payload.
        if (($e instanceof ValidateException || $e instanceof BusinessException)
            && self::wantsJson($request)) {
            return json([
                'code' => $e->getCode(),
                'message' => $e->getMessage(),
            ]);
        }

        return parent::render($request, $e);
    }

    /**
     * JSON is appropriate only for the strict AJAX marker the panel's own
     * requests carry (see app\middleware\CheckAjaxRequest). Anything without
     * that marker — including a non-Request argument — falls back to the
     * framework's HTML rendering.
     */
    public static function wantsJson($request): bool
    {
        return is_object($request)
            && method_exists($request, 'isAjax')
            && $request->isAjax(true);
    }
}